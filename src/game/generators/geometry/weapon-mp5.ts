/**
 * MP5：短枪管、筒形护木、枪管上方的拉机柄管（拉机柄在左侧）、环形准星护圈、鼓形照门、
 * 微弧弹匣、聚合物握把与伸缩托（拉出状态）。
 * 坐标：root 原点在握把顶端虎口处，枪管朝 +Z，轴线高度 0.058；全长约 0.755m（Z -0.335..0.420）。
 */

import { arcBand, box, createLayer, lathe, loft, outline, profile, rect, ring, rod, sec, shell } from './weapon-kit'
import type { Pt, WeaponBlueprint } from './weapon-kit'

/** 枪管轴线高度 */
const AXIS = 0.058
/** 拉机柄管轴线高度 */
const COCK = 0.088
/** 机匣半宽 */
const HALF = 0.0185

/**
 * 生成 MP5 的模型蓝图。
 * @returns 发黑钢、聚合物、亮钢三个图层与枪口位置
 */
export function buildMp5(): WeaponBlueprint {
  const metal = createLayer('gunmetal', {}, [6, 6])
  const poly = createLayer('polymer', { color: 0x1b1c1f }, [8, 8])
  const steel = createLayer('steel', { roughness: 0.42 }, [8, 8])

  /* ── 机匣 ── */

  // 冲压上机匣：圆角矩形截面，前端收进护木
  metal.add(
    loft(
      [
        sec(-0.128, 0.036, 0.09, 0.0175, 3.2),
        sec(-0.12, 0.034, 0.092, HALF, 3.2),
        sec(0.176, 0.034, 0.092, HALF, 3.2),
        sec(0.19, 0.036, 0.09, 0.0172, 3.2),
      ],
      { segments: 24 },
    ),
  )
  // 两侧的冲压加强筋、顶部的瞄具卡槽凸台
  for (const side of [-1, 1]) {
    metal.add(box(0.0014, 0.005, 0.2, side * 0.0187, 0.047, 0.02, 0.0005))
    for (const z of [-0.045, 0.02, 0.095]) metal.add(box(0.004, 0.003, 0.028, side * 0.009, 0.0925, z, 0.0008))
  }
  // 机匣尾盖与左侧背带环
  metal.add(
    loft(
      [
        sec(-0.142, 0.04, 0.088, 0.016, 3),
        sec(-0.138, 0.034, 0.093, 0.0195, 3.2),
        sec(-0.127, 0.034, 0.093, 0.0195, 3.2),
      ],
      { segments: 24 },
    ),
  )
  metal.add(ring(0.006, 0.0012, 0.0205, 0.052, -0.134, 'z', 14, 6))

  // 右侧抛壳窗：窗框 + 露出的枪机
  metal.add(
    profile(rect(0.016, 0.089, 0.052, 0.084, 0.003), 0.0016, {
      bevel: 0.0005,
      x: -0.0188,
      holes: [rect(0.02, 0.085, 0.056, 0.08, 0.002)],
    }),
  )
  steel.add(box(0.001, 0.024, 0.065, -0.0187, 0.068, 0.0525, 0.0003))

  // 销轴（贯穿两侧，略微凸出）
  const pins: readonly Pt[] = [
    [-0.1, 0.03],
    [-0.06, 0.022],
    [0.075, 0.026],
    [0.165, 0.046],
  ]
  for (const [z, y] of pins) {
    const reach = y > 0.04 ? 0.0195 : 0.0178
    steel.add(rod(0.0027, [-reach, y, z], [reach, y, z], 10))
  }

  /* ── 拉机柄管与枪管 ── */

  metal.add(
    lathe(
      [
        [0.168, 0.0115],
        [0.35, 0.0115],
        [0.35, 0.0126],
        [0.36, 0.0126],
        [0.3625, 0.011],
      ],
      COCK,
      0,
      24,
    ),
  )
  // 左侧的拉机柄滑槽、拉机柄与握球
  metal.add(box(0.0014, 0.0055, 0.115, 0.0114, 0.09, 0.262, 0.0005))
  metal.add(box(0.0014, 0.009, 0.008, 0.0114, 0.0925, 0.209, 0.0005))
  steel.add(rod(0.0034, [0.01, 0.09, 0.312], [0.03, 0.0945, 0.3075], 10))
  poly.add(rod(0.0058, [0.027, 0.0938, 0.3082], [0.041, 0.097, 0.305], 12, 0.0052))

  // 枪管：前端三凸耳卡座
  metal.add(
    lathe(
      [
        [0.17, 0.0095],
        [0.34, 0.0095],
        [0.344, 0.0082],
        [0.39, 0.0082],
        [0.39, 0.0094],
        [0.4, 0.0094],
        [0.4, 0.0082],
        [0.4195, 0.0082],
        [0.42, 0.0077],
        [0.42, 0.0045],
        [0.4, 0.0045],
        [0.4, 0],
      ],
      AXIS,
      0,
      20,
    ),
  )
  for (let i = 0; i < 3; i++) {
    const lug = box(0.0055, 0.003, 0.007, 0, 0.0098, 0.395, 0.0006)
    lug.rotateZ((i * Math.PI * 2) / 3)
    lug.translate(0, AXIS, 0)
    metal.add(lug)
  }

  /* ── 瞄具 ── */

  // 准星座（套住枪管与拉机柄管前端）、环形护圈、准星
  metal.add(
    profile(
      outline(
        [
          [0.336, 0.046, 0.004],
          [0.362, 0.046, 0.004],
          [0.362, 0.1],
          [0.358, 0.106],
          [0.342, 0.106],
          [0.336, 0.1],
        ],
        2,
      ),
      0.022,
      { bevel: 0.0015 },
    ),
  )
  metal.add(shell(0.0135, 0.0115, 0.342, 0.358, 0.117, 0, 24))
  metal.add(rod(0.0012, [0, 0.105, 0.35], [0, 0.1175, 0.35], 8))
  metal.add(ring(0.006, 0.0012, 0.0135, 0.06, 0.349, 'z', 14, 6))

  // 鼓形照门：底座、转鼓、照门缺口、风偏螺钉
  metal.add(box(0.026, 0.006, 0.032, 0, 0.094, -0.085, 0.0012))
  metal.add(
    loft(
      [
        { t: 0.096, c: -0.085, a: 0.0105, w: 0.0105 },
        { t: 0.0975, c: -0.085, a: 0.0115, w: 0.0115 },
        { t: 0.111, c: -0.085, a: 0.0115, w: 0.0115 },
        { t: 0.1135, c: -0.085, a: 0.0095, w: 0.0095 },
      ],
      { axis: 'y', segments: 20 },
    ),
  )
  for (const side of [-1, 1]) metal.add(box(0.004, 0.005, 0.004, side * 0.0045, 0.1155, -0.091, 0.0006))
  metal.add(rod(0.003, [-0.0155, 0.095, -0.085], [0.0155, 0.095, -0.085], 8))

  /* ── 握把组件 ── */

  // 聚合物下机匣（扳机组外壳）
  poly.add(
    profile(
      outline([
        [-0.118, 0.04],
        [-0.118, 0.024, 0.005],
        [-0.05, 0.012, 0.004],
        [0.092, 0.012, 0.003],
        [0.092, 0.04],
      ]),
      0.033,
      { bevel: 0.002, bevelSegments: 2 },
    ),
  )
  // 握把：向后下方倾斜
  poly.add(
    loft(
      [
        { t: -0.104, c: -0.04, a: 0.019, w: 0.0135, n: 2.8 },
        { t: -0.1, c: -0.039, a: 0.0225, w: 0.016, n: 2.8 },
        { t: -0.06, c: -0.024, a: 0.0215, w: 0.016, n: 2.8 },
        { t: -0.02, c: -0.01, a: 0.021, w: 0.0155, n: 2.8 },
        { t: 0.014, c: 0, a: 0.022, w: 0.0155, n: 2.8 },
      ],
      { axis: 'y', segments: 20 },
    ),
  )
  // 扳机护圈（与下机匣一体）
  poly.add(
    profile(
      outline([
        [0.016, 0.014],
        [0.082, 0.014],
        [0.082, -0.028, 0.01],
        [0.016, -0.028, 0.01],
      ]),
      0.012,
      {
        bevel: 0.0008,
        holes: [
          outline([
            [0.019, 0.0115],
            [0.079, 0.0115],
            [0.079, -0.025, 0.008],
            [0.019, -0.025, 0.008],
          ]),
        ],
      },
    ),
  )
  // 扳机
  metal.add(
    profile(
      outline(
        [
          [0.036, 0.014],
          [0.045, 0.014],
          [0.0435, 0.002, 0.004],
          [0.04, -0.01, 0.003],
          [0.043, -0.017, 0.002],
          [0.039, -0.018, 0.002],
          [0.035, -0.008, 0.004],
          [0.0365, 0.004, 0.004],
        ],
        2,
      ),
      0.006,
      { bevel: 0.0008 },
    ),
  )
  // 快慢机：左侧拨杆，右侧指示轴
  metal.add(rod(0.0055, [0.0165, 0.03, -0.012], [0.0192, 0.03, -0.012], 12))
  metal.add(
    profile(
      outline(
        [
          [-0.016, 0.027, 0.002],
          [0.014, 0.028, 0.002],
          [0.014, 0.033, 0.002],
          [-0.016, 0.034, 0.002],
        ],
        2,
      ),
      0.002,
      { bevel: 0.0006, x: 0.0198 },
    ),
  )
  metal.add(rod(0.0045, [-0.0165, 0.03, -0.012], [-0.0185, 0.03, -0.012], 10))

  /* ── 弹匣 ── */

  // 弹匣井与后方的拨片式弹匣卡榫
  metal.add(
    profile(
      outline([
        [0.092, 0.04],
        [0.092, -0.004, 0.003],
        [0.144, -0.004, 0.003],
        [0.15, 0.04],
      ]),
      0.03,
      { bevel: 0.0015 },
    ),
  )
  metal.add(
    profile(
      outline(
        [
          [0.083, 0.012],
          [0.0915, 0.012],
          [0.0915, -0.006, 0.002],
          [0.087, -0.018, 0.002],
          [0.083, -0.017, 0.002],
          [0.0855, -0.005, 0.003],
        ],
        2,
      ),
      0.012,
      { bevel: 0.0008 },
    ),
  )
  // 微弧弹匣：圆心在前方，越往下越向前弯
  const magZ = 0.72
  const magY = 0.035
  metal.add(profile(arcBand(magZ, magY, 0.584, 0.616, -0.02, 0.3, 8), 0.024, { bevel: 0.002 }))
  metal.add(profile(arcBand(magZ, magY, 0.593, 0.607, 0.03, 0.285, 8), 0.0262, { bevel: 0.001 }))
  metal.add(profile(arcBand(magZ, magY, 0.582, 0.618, 0.297, 0.31, 1), 0.027, { bevel: 0.001 }))

  /* ── 筒形护木 ── */

  poly.add(
    loft(
      [
        sec(0.186, 0.03, 0.08, 0.019),
        sec(0.194, 0.026, 0.082, 0.0215),
        sec(0.3, 0.027, 0.082, 0.021),
        sec(0.326, 0.03, 0.08, 0.0195),
        sec(0.333, 0.034, 0.078, 0.017),
      ],
      { segments: 24 },
    ),
  )
  // 防滑环筋：两端不封口，收进护木表面以内
  for (const z of [0.214, 0.238, 0.262, 0.286]) {
    poly.add(
      loft(
        [
          sec(z - 0.006, 0.0278, 0.0808, 0.0204),
          sec(z - 0.004, 0.0252, 0.0832, 0.0224),
          sec(z + 0.004, 0.0252, 0.0832, 0.0224),
          sec(z + 0.006, 0.0278, 0.0808, 0.0204),
        ],
        { segments: 24, caps: 'none' },
      ),
    )
  }
  // 护木固定销
  steel.add(rod(0.0026, [-0.0222, 0.036, 0.318], [0.0222, 0.036, 0.318], 10))

  /* ── 伸缩托（拉出） ── */

  for (const side of [-1, 1]) {
    // 导轨沿机匣两侧的滑槽伸出，前端止于抛壳窗之后
    steel.add(rod(0.0042, [side * 0.0228, 0.07, -0.322], [side * 0.0228, 0.07, 0.004], 10))
    metal.add(box(0.01, 0.014, 0.012, side * 0.0225, 0.07, -0.119, 0.0015))
    metal.add(box(0.008, 0.011, 0.01, side * 0.0222, 0.07, 0.002, 0.0015))
  }
  // 托底板：高而扁的圆角板，后缘收圆
  poly.add(
    loft(
      [
        sec(-0.335, 0.008, 0.09, 0.0235, 3.5),
        sec(-0.3315, 0.001, 0.097, 0.0275, 3.5),
        sec(-0.32, -0.001, 0.099, 0.028, 3.5),
        sec(-0.316, 0.002, 0.096, 0.0265, 3.5),
      ],
      { segments: 24 },
    ),
  )
  // 托底板前的导轨连接座
  metal.add(box(0.05, 0.016, 0.01, 0, 0.07, -0.312, 0.002))

  return { layers: [metal.build(), poly.build(), steel.build()], muzzle: [0.42, AXIS] }
}
