/**
 * Barrett M82A1：半自动反器材狙击步枪。哑光深灰机匣、带散热凹槽的长枪管、箭头形双腔制退器、
 * 顶部长导轨与大型狙击镜、收拢的两脚架与提把、前倾的 10 发直弹匣、带橡胶后座垫与托腮的枪托。
 * 坐标：root 原点在握把顶端，枪管朝 +Z，轴线高度 0.072；全长约 1.13m（Z -0.33..0.80）。
 */

import { box, createLayer, lathe, outline, profile, rect, ring, rod, sec, loft, shell } from './weapon-kit'
import type { Pt, WeaponBlueprint } from './weapon-kit'

/** 枪管轴线高度 */
const AXIS = 0.072
/** 狙击镜轴线高度 */
const SCOPE_Y = 0.134
/** 枪口位置 */
const MUZZLE_Z = 0.8

/**
 * 生成 Barrett M82A1 的模型蓝图。
 * @returns 发黑钢、黑色聚合物、橡胶三个图层与枪口位置
 */
export function buildBarrett(): WeaponBlueprint {
  const metal = createLayer('gunmetal', { color: 0x2b2d30 }, [6, 6])
  const black = createLayer('polymer', { color: 0x151618, roughness: 0.6 }, [8, 8])
  const rubber = createLayer('rubber', {}, [10, 10])

  /* ── 机匣 ── */

  // 上机匣：长方体，后部略低
  metal.add(
    profile(
      outline([
        [-0.15, 0.1, 0.004],
        [0.25, 0.1, 0.004],
        [0.25, 0.044, 0.004],
        [-0.15, 0.044, 0.004],
      ]),
      0.042,
      { bevel: 0.004, bevelSegments: 2 },
    ),
  )
  // 机匣下方的弹匣井与下机匣
  metal.add(box(0.042, 0.03, 0.12, 0, 0.034, 0.145, 0.003))
  black.add(
    profile(
      outline([
        [-0.15, 0.046],
        [0.04, 0.046],
        [0.04, 0.03, 0.004],
        [-0.15, 0.022, 0.004],
      ]),
      0.036,
      { bevel: 0.003 },
    ),
  )
  // 右侧抛壳窗（凹槽示意）与拉机柄
  metal.add(box(0.001, 0.02, 0.1, -0.0215, 0.082, 0.1, 0.0004))
  metal.add(rod(0.0048, [-0.021, 0.082, 0.17], [-0.052, 0.082, 0.125], 10))
  metal.add(rod(0.009, [-0.052, 0.082, 0.125], [-0.062, 0.082, 0.119], 12))
  // 螺钉与销轴
  const pins: readonly Pt[] = [
    [-0.12, 0.06],
    [-0.04, 0.085],
    [0.06, 0.055],
    [0.2, 0.06],
  ]
  for (const [z, y] of pins) metal.add(rod(0.003, [-0.0222, y, z], [0.0222, y, z], 10))

  /* ── 枪托 ── */

  black.add(
    profile(
      outline([
        [-0.14, 0.098, 0.004],
        [-0.31, 0.088, 0.006],
        [-0.31, -0.03, 0.006],
        [-0.25, -0.032, 0.008],
        [-0.2, 0.026, 0.01],
        [-0.14, 0.044, 0.004],
      ]),
      0.036,
      { bevel: 0.003, bevelSegments: 2 },
    ),
  )
  // 托腮
  black.add(box(0.034, 0.024, 0.1, 0, 0.1, -0.225, 0.006))
  // 橡胶后座垫
  rubber.add(box(0.044, 0.128, 0.022, 0, 0.03, -0.322, 0.005))
  // 枪托下方的后脚架
  metal.add(rod(0.005, [0, -0.02, -0.26], [0, -0.075, -0.255], 10))
  // 背带环
  metal.add(ring(0.006, 0.0013, 0.0215, 0.07, -0.15, 'z', 14, 6))

  /* ── 握把、扳机护圈 ── */

  black.add(
    profile(
      outline([
        [-0.014, 0.046],
        [0.034, 0.046],
        [0.026, -0.02, 0.004],
        [0.004, -0.098, 0.006],
        [-0.04, -0.098, 0.004],
        [-0.042, -0.05, 0.004],
      ]),
      0.03,
      { bevel: 0.004, bevelSegments: 2 },
    ),
  )
  // 扳机护圈：长圆环
  metal.add(
    profile(rect(0.03, 0.12, -0.04, 0.042, 0.012), 0.008, {
      bevel: 0.0012,
      holes: [rect(0.038, 0.112, -0.032, 0.034, 0.008)],
    }),
  )
  // 扳机
  metal.add(
    profile(
      outline(
        [
          [0.05, 0.03],
          [0.058, 0.03],
          [0.056, 0.0, 0.004],
          [0.048, -0.022, 0.003],
          [0.044, -0.02, 0.002],
          [0.049, 0.0, 0.004],
        ],
        2,
      ),
      0.005,
      { bevel: 0.0008 },
    ),
  )

  /* ── 弹匣：10 发直插盒形，略前倾 ── */

  black.add(
    profile(
      outline([
        [0.115, 0.022],
        [0.19, 0.022],
        [0.206, -0.086, 0.004],
        [0.13, -0.086, 0.004],
      ]),
      0.032,
      { bevel: 0.002 },
    ),
  )
  // 弹匣两侧的压筋、底板
  for (const side of [-1, 1]) black.add(box(0.0014, 0.09, 0.004, side * 0.0165, -0.03, 0.162, 0.0005))
  metal.add(box(0.036, 0.008, 0.086, 0, -0.088, 0.168, 0.0015))
  // 弹匣卡榫
  metal.add(box(0.012, 0.016, 0.01, 0, 0.0, 0.108, 0.001))

  /* ── 导轨与狙击镜 ── */

  // 顶部长导轨
  metal.add(box(0.022, 0.008, 0.42, 0, 0.104, 0.07, 0.001))
  for (let i = 0; i < 26; i++) metal.add(box(0.026, 0.0035, 0.007, 0, 0.1105, -0.13 + i * 0.016, 0.0004))

  // 狙击镜：目镜与物镜喇叭口、中段调节座
  metal.add(
    lathe(
      [
        [-0.15, 0],
        [-0.15, 0.0185],
        [-0.145, 0.0235],
        [-0.125, 0.0215],
        [-0.1, 0.0175],
        [-0.085, 0.0165],
        [0.1, 0.0165],
        [0.14, 0.0175],
        [0.19, 0.0235],
        [0.25, 0.0305],
        [0.255, 0.0305],
        [0.255, 0],
      ],
      SCOPE_Y,
      0,
      28,
    ),
  )
  // 物镜内凹的镜片
  metal.add(shell(0.0305, 0.0265, 0.2, 0.255, SCOPE_Y, 0, 28))
  // 中段调节座：顶部高低、右侧风偏
  metal.add(lathe([[-0.02, 0.0165], [-0.02, 0.022], [0.03, 0.022], [0.03, 0.0165]], SCOPE_Y, 0, 20))
  metal.add(rod(0.0085, [0, SCOPE_Y + 0.02, 0.005], [0, SCOPE_Y + 0.036, 0.005], 14))
  metal.add(rod(0.0085, [-0.02, SCOPE_Y, 0.005], [-0.036, SCOPE_Y, 0.005], 14))
  // 目镜端防眩圈与调焦环
  metal.add(lathe([[-0.095, 0.0165], [-0.095, 0.02], [-0.065, 0.02], [-0.065, 0.0165]], SCOPE_Y, 0, 22))
  // 前后两道镜环与底座
  for (const z of [-0.06, 0.12]) {
    metal.add(lathe([[z - 0.011, 0.0165], [z - 0.011, 0.0205], [z + 0.011, 0.0205], [z + 0.011, 0.0165]], SCOPE_Y, 0, 22))
    metal.add(box(0.026, 0.018, 0.022, 0, 0.113, z, 0.002))
  }

  /* ── 枪管 ── */

  const barrel: Pt[] = [
    [0.15, 0.0185],
    [0.265, 0.0185],
    [0.265, 0.0155],
    [0.29, 0.0155],
    [0.29, 0.0125],
  ]
  // 散热凹槽：一段凸起、一段凹槽交替
  for (let z = 0.3; z < 0.62; z += 0.04) {
    barrel.push([z, 0.0125], [z + 0.026, 0.0125], [z + 0.027, 0.0105], [z + 0.039, 0.0105], [z + 0.04, 0.0125])
  }
  barrel.push([0.66, 0.0125], [0.67, 0.0125])
  metal.add(lathe(barrel, AXIS, 0, 20))

  /* ── 制退器：两腔箭头 ── */

  // 核心管
  metal.add(
    lathe(
      [
        [0.665, 0.0175],
        [0.8, 0.0175],
        [0.8, 0.0085],
        [0.665, 0.0085],
      ],
      AXIS,
      0,
      20,
    ),
  )
  // 两侧宽板：侧面开出两个排气腔，前端斜切成箭头
  metal.add(
    profile(
      outline([
        [0.675, AXIS + 0.026, 0.004],
        [0.775, AXIS + 0.026, 0.004],
        [0.8, AXIS + 0.008],
        [0.8, AXIS - 0.008],
        [0.775, AXIS - 0.026, 0.004],
        [0.675, AXIS - 0.026, 0.004],
      ]),
      0.05,
      {
        bevel: 0.003,
        bevelSegments: 2,
        holes: [rect(0.69, 0.725, AXIS - 0.012, AXIS + 0.012, 0.004), rect(0.737, 0.772, AXIS - 0.012, AXIS + 0.012, 0.004)],
      },
    ),
  )
  // 侧面 V 形箭头刻线
  for (const x of [-0.0255, 0.0255]) {
    metal.add(rod(0.0022, [x, AXIS + 0.02, 0.7], [x, AXIS, 0.745], 6))
    metal.add(rod(0.0022, [x, AXIS - 0.02, 0.7], [x, AXIS, 0.745], 6))
  }

  /* ── 提把（折叠状态）与前端两脚架 ── */

  black.add(
    profile(
      outline([
        [0.32, 0.09],
        [0.5, 0.09],
        [0.5, 0.108, 0.006],
        [0.32, 0.108, 0.006],
      ]),
      0.01,
      { bevel: 0.0015, holes: [rect(0.336, 0.484, 0.095, 0.103, 0.003)] },
    ),
  )
  for (const z of [0.325, 0.495]) metal.add(box(0.014, 0.012, 0.014, 0, 0.087, z, 0.001))

  // 两脚架：转轴座在枪管前段下方，两条腿向后收拢贴住枪管
  metal.add(box(0.07, 0.016, 0.03, 0, 0.056, 0.52, 0.002))
  for (const side of [-1, 1]) {
    const x = side * 0.03
    metal.add(rod(0.0042, [x, 0.052, 0.52], [x, 0.046, 0.34], 8))
    metal.add(box(0.012, 0.008, 0.02, x, 0.044, 0.335, 0.001))
    metal.add(rod(0.0055, [x * 0.5, 0.058, 0.52], [x, 0.052, 0.52], 8))
  }

  // 机匣前端的枪管固定套
  const collar = loft(
    [
      sec(0.245, 0.044, 0.1, 0.0235, 3),
      sec(0.265, 0.05, 0.094, 0.0205, 3),
    ],
    { segments: 20 },
  )
  metal.add(collar)

  return { layers: [metal.build(), black.build(), rubber.build()], muzzle: [MUZZLE_Z, AXIS] }
}
