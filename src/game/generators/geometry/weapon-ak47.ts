/**
 * AK-47：冲压机匣 + 带加强筋的机匣盖、枪管上方的导气管、斜切枪口、弧形弹匣、木质枪托 / 握把 / 护木。
 * 坐标：root 原点在握把顶端虎口处，枪管朝 +Z，轴线高度 0.062；全长约 0.985m（Z -0.365..0.620）。
 */

import {
  arcBand,
  box,
  createLayer,
  grainAlong,
  lathe,
  loft,
  outline,
  profile,
  ring,
  rod,
  sec,
  shear,
  tube,
} from './weapon-kit'
import type { WeaponBlueprint } from './weapon-kit'

/** 枪管轴线高度 */
const AXIS = 0.062
/** 导气管轴线高度 */
const GAS = 0.092
/** 机匣半宽 */
const HALF = 0.018

/**
 * 生成 AK-47 的模型蓝图。
 * @returns 发黑钢、木件、亮钢三个图层与枪口位置
 */
export function buildAk47(): WeaponBlueprint {
  const metal = createLayer('gunmetal', {}, [6, 6])
  const wood = createLayer('wood', {}, [4, 9])
  const steel = createLayer('steel', { roughness: 0.42 }, [8, 8])

  /* ── 机匣 ── */

  // 冲压机匣：后端下缘收斜
  metal.add(
    profile(
      outline([
        [-0.118, 0.084],
        [-0.12, 0.05, 0.006],
        [-0.106, 0.022, 0.006],
        [0.168, 0.022, 0.003],
        [0.168, 0.084, 0.002],
      ]),
      HALF * 2,
      { bevel: 0.0015 },
    ),
  )
  // 前节套（比机匣略宽）
  metal.add(box(0.0375, 0.05, 0.054, 0, 0.058, 0.145, 0.0012))

  // 机匣盖：拱顶，后端下弯
  metal.add(
    loft(
      [
        sec(-0.117, 0.074, 0.088, 0.015),
        sec(-0.11, 0.07, 0.098, 0.0165),
        sec(-0.092, 0.066, 0.1045, 0.0172),
        sec(0.11, 0.066, 0.106, 0.0172),
        sec(0.118, 0.066, 0.1055, 0.0168),
      ],
      { segments: 20 },
    ),
  )
  // 机匣盖上的横向加强筋
  for (const z of [-0.075, -0.04, -0.005, 0.03, 0.065]) {
    metal.add(
      loft(
        [
          sec(z - 0.0055, 0.066, 0.1048, 0.017),
          sec(z - 0.003, 0.066, 0.1066, 0.0183),
          sec(z + 0.003, 0.066, 0.1066, 0.0183),
          sec(z + 0.0055, 0.066, 0.1048, 0.017),
        ],
        { segments: 20, caps: 'none' },
      ),
    )
  }

  // 右侧露出的枪机框与拉机柄
  steel.add(box(0.005, 0.012, 0.094, -0.0168, 0.088, 0.069, 0.0008))
  steel.add(rod(0.0042, [-0.018, 0.088, 0.108], [-0.043, 0.0905, 0.104], 10, 0.0034))

  // 快慢机（右侧的长拨片）、轴与指挡
  metal.add(
    profile(
      outline(
        [
          [-0.046, 0.05, 0.004],
          [-0.036, 0.043, 0.004],
          [0.06, 0.05],
          [0.082, 0.05, 0.002],
          [0.084, 0.06, 0.002],
          [0.06, 0.061],
          [-0.036, 0.062, 0.004],
          [-0.046, 0.056, 0.003],
        ],
        2,
      ),
      0.0016,
      { bevel: 0.0005, x: -HALF - 0.0008 },
    ),
  )
  metal.add(rod(0.005, [-HALF, 0.0525, -0.036], [-HALF - 0.003, 0.0525, -0.036], 10))
  metal.add(box(0.007, 0.004, 0.012, -HALF - 0.0045, 0.0555, 0.077, 0.0008))

  // 铆钉与销轴（贯穿两侧，略微凸出）
  const pins: readonly (readonly [number, number])[] = [
    [-0.104, 0.036],
    [-0.104, 0.07],
    [-0.09, 0.052],
    [0.012, 0.04],
    [0.034, 0.05],
    [0.056, 0.044],
    [0.134, 0.04],
    [0.154, 0.04],
    [0.134, 0.072],
    [0.156, 0.07],
  ]
  for (const [z, y] of pins) {
    const reach = z > 0.118 ? 0.0196 : HALF + 0.0008
    metal.add(rod(0.0024, [-reach, y, z], [reach, y, z], 8))
  }

  /* ── 扳机组 ── */

  // 扳机护圈（钢带弯成的环）
  metal.add(
    profile(
      outline([
        [0.016, 0.026],
        [0.076, 0.026],
        [0.076, -0.024, 0.009],
        [0.016, -0.024, 0.009],
      ]),
      0.011,
      {
        bevel: 0.0007,
        holes: [
          outline([
            [0.0185, 0.0235],
            [0.0735, 0.0235],
            [0.0735, -0.0215, 0.007],
            [0.0185, -0.0215, 0.007],
          ]),
        ],
      },
    ),
  )
  // 扳机
  metal.add(
    profile(
      outline(
        [
          [0.036, 0.026],
          [0.045, 0.026],
          [0.0435, 0.01, 0.004],
          [0.04, -0.004, 0.003],
          [0.043, -0.012, 0.002],
          [0.039, -0.013, 0.002],
          [0.035, -0.002, 0.004],
          [0.0365, 0.012, 0.004],
        ],
        2,
      ),
      0.006,
      { bevel: 0.0008 },
    ),
  )
  // 弹匣卡榫
  metal.add(
    profile(
      outline(
        [
          [0.076, 0.024],
          [0.083, 0.024],
          [0.0845, -0.004, 0.003],
          [0.081, -0.019, 0.002],
          [0.077, -0.019, 0.002],
          [0.0785, -0.004, 0.003],
        ],
        2,
      ),
      0.009,
      { bevel: 0.0008 },
    ),
  )

  /* ── 弧形弹匣 ── */

  // 圆心在前上方，弹匣越往下越向前弯
  const magZ = 0.41504
  const magY = 0.05397
  metal.add(profile(arcBand(magZ, magY, 0.268, 0.332, 0.06, 0.76, 10), 0.026, { bevel: 0.002 }))
  // 两侧的纵向加强筋、背脊、底板
  metal.add(profile(arcBand(magZ, magY, 0.289, 0.311, 0.14, 0.72, 10), 0.0286, { bevel: 0.0012 }))
  metal.add(profile(arcBand(magZ, magY, 0.3305, 0.3348, 0.1, 0.74, 10), 0.012, { bevel: 0.001 }))
  metal.add(profile(arcBand(magZ, magY, 0.2655, 0.3345, 0.752, 0.776, 1), 0.029, { bevel: 0.001 }))

  /* ── 枪管组 ── */

  // 枪管：根部加粗
  metal.add(
    lathe(
      [
        [0.16, 0.0105],
        [0.2, 0.0105],
        [0.204, 0.0088],
        [0.592, 0.0088],
      ],
      AXIS,
    ),
  )
  // 斜切枪口防跳器（下唇在前），带内膛
  metal.add(
    shear(
      lathe(
        [
          [0.584, 0.0098],
          [0.59, 0.011],
          [0.612, 0.011],
          [0.612, 0.0048],
          [0.592, 0.0048],
          [0.592, 0],
        ],
        AXIS,
        0,
        20,
      ),
      0.61,
      AXIS,
      0.7,
    ),
  )

  // 准星座：箍、立柱、两片护耳、准星
  metal.add(
    loft(
      [
        sec(0.552, 0.049, 0.078, 0.0105, 3),
        sec(0.556, 0.048, 0.08, 0.0115, 3),
        sec(0.584, 0.048, 0.08, 0.0115, 3),
        sec(0.588, 0.049, 0.078, 0.0105, 3),
      ],
      { segments: 16 },
    ),
  )
  metal.add(
    profile(
      outline(
        [
          [0.56, 0.076],
          [0.584, 0.076],
          [0.582, 0.1, 0.004],
          [0.576, 0.104],
          [0.566, 0.104],
          [0.562, 0.1, 0.004],
        ],
        2,
      ),
      0.01,
      { bevel: 0.001 },
    ),
  )
  metal.add(box(0.0158, 0.004, 0.02, 0, 0.102, 0.572, 0.0008))
  for (const side of [-1, 1]) {
    metal.add(
      profile(
        outline(
          [
            [0.563, 0.1],
            [0.581, 0.1],
            [0.581, 0.116, 0.004],
            [0.577, 0.122, 0.002],
            [0.567, 0.122, 0.002],
            [0.563, 0.116, 0.004],
          ],
          2,
        ),
        0.0028,
        { bevel: 0.0007, x: side * 0.0065 },
      ),
    )
  }
  metal.add(rod(0.0016, [0, 0.103, 0.572], [0, 0.1185, 0.572], 8))

  // 导气箍（连接枪管与上方的导气管）与左侧背带环
  metal.add(
    profile(
      outline(
        [
          [0.43, 0.05, 0.003],
          [0.464, 0.05, 0.003],
          [0.466, 0.072],
          [0.456, 0.1015, 0.003],
          [0.438, 0.1015, 0.003],
          [0.432, 0.08],
        ],
        2,
      ),
      0.021,
      { bevel: 0.0015 },
    ),
  )
  metal.add(ring(0.006, 0.0012, 0.0155, 0.06, 0.448, 'z', 14, 6))
  // 导气管
  metal.add(
    lathe(
      [
        [0.338, 0.0082],
        [0.426, 0.0082],
        [0.426, 0.0096],
        [0.44, 0.0096],
      ],
      GAS,
    ),
  )

  // 护木前箍与上护木两端的铁箍
  metal.add(
    loft(
      [
        sec(0.342, 0.036, 0.081, 0.0185, 4),
        sec(0.344, 0.034, 0.083, 0.02, 4),
        sec(0.354, 0.034, 0.083, 0.02, 4),
        sec(0.356, 0.036, 0.081, 0.0185, 4),
      ],
      { segments: 16 },
    ),
  )
  for (const z of [0.188, 0.334]) {
    metal.add(loft([sec(z, 0.0755, 0.1088, 0.0171, 2.3), sec(z + 0.007, 0.0755, 0.1088, 0.0171, 2.3)], { segments: 16 }))
  }

  // 表尺座、表尺板、照门缺口
  metal.add(
    profile(
      outline(
        [
          [0.118, 0.082],
          [0.18, 0.082],
          [0.18, 0.097, 0.003],
          [0.162, 0.1035, 0.003],
          [0.118, 0.1005, 0.002],
        ],
        2,
      ),
      0.026,
      { bevel: 0.0012 },
    ),
  )
  metal.add(box(0.012, 0.004, 0.058, 0, 0.1055, 0.151, 0.0008))
  metal.add(box(0.016, 0.005, 0.007, 0, 0.1085, 0.1455, 0.0008))
  for (const side of [-1, 1]) metal.add(box(0.0046, 0.008, 0.004, side * 0.0044, 0.1115, 0.1235, 0.0006))
  metal.add(box(0.0134, 0.004, 0.004, 0, 0.1075, 0.1235, 0.0006))

  // 枪管下的通条
  steel.add(rod(0.0024, [0, 0.0468, 0.352], [0, 0.0468, 0.596], 8))
  steel.add(tube(0.0034, 0.594, 0.602, 0.0468, 0, 8))

  /* ── 木件 ── */

  // 枪托：前端接机匣尾，向后逐渐加高并下沉；木纹顺着枪托的走向
  wood.addGrain(
    grainAlong(0.244, 0.049),
    loft(
      [
        sec(-0.352, -0.05, 0.058, 0.0175, 3.2),
        sec(-0.3, -0.04, 0.064, 0.019, 3.2),
        sec(-0.2, -0.012, 0.072, 0.0185, 3.2),
        sec(-0.135, 0.014, 0.079, 0.0175, 3.2),
        sec(-0.108, 0.024, 0.082, 0.0165, 3.2),
      ],
      { segments: 20 },
    ),
  )
  // 托底钢板与托底背带环
  metal.add(
    loft(
      [
        sec(-0.365, -0.048, 0.056, 0.016, 3.5),
        sec(-0.3635, -0.052, 0.06, 0.0185, 3.5),
        sec(-0.352, -0.052, 0.06, 0.0185, 3.5),
      ],
      { segments: 20 },
    ),
  )
  metal.add(ring(0.008, 0.0014, 0, -0.043, -0.285, 'x', 14, 6))

  // 握把：向后下方倾斜，木纹顺着握把走
  wood.addGrain(
    grainAlong(0.03, 0.11),
    loft(
      [
        { t: -0.098, c: -0.034, a: 0.019, w: 0.013, n: 3 },
        { t: -0.094, c: -0.033, a: 0.022, w: 0.0155, n: 3 },
        { t: -0.06, c: -0.021, a: 0.021, w: 0.0155, n: 3 },
        { t: -0.02, c: -0.008, a: 0.0205, w: 0.015, n: 3 },
        { t: 0.012, c: 0.002, a: 0.021, w: 0.0145, n: 3 },
        { t: 0.024, c: 0.005, a: 0.021, w: 0.014, n: 3 },
      ],
      { axis: 'y', segments: 20 },
    ),
  )

  // 下护木（左手托持处，中段略鼓）与上护木（包住导气管）
  wood.add(
    loft(
      [
        sec(0.17, 0.036, 0.08, 0.0185, 3.2),
        sec(0.176, 0.032, 0.08, 0.0205, 3.2),
        sec(0.215, 0.029, 0.08, 0.0225, 3.2),
        sec(0.29, 0.029, 0.08, 0.0225, 3.2),
        sec(0.336, 0.032, 0.08, 0.0205, 3.2),
        sec(0.344, 0.035, 0.08, 0.019, 3.2),
      ],
      { segments: 20 },
    ),
  )
  wood.add(
    loft(
      [
        sec(0.19, 0.078, 0.105, 0.015, 2.3),
        sec(0.196, 0.076, 0.108, 0.0165, 2.3),
        sec(0.332, 0.076, 0.108, 0.0165, 2.3),
        sec(0.338, 0.078, 0.105, 0.015, 2.3),
      ],
      { segments: 20 },
    ),
  )

  return { layers: [metal.build(), wood.build(), steel.build()], muzzle: [0.62, AXIS] }
}
