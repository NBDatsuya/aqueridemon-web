/**
 * QBZ-95：无托结构（弹匣与机匣在握把后方）、一体式提把兼瞄具基座、聚合物枪身、弧形弹匣、
 * 兼作前握把的大护圈、带护圈的高准星。
 * 坐标：root 原点在握把顶端虎口处，枪管朝 +Z，轴线高度 0.064；全长约 0.753m（Z -0.323..0.430）。
 */

import { arcBand, box, createLayer, lathe, loft, outline, profile, rect, ring, rod, sec, shell } from './weapon-kit'
import type { Pt, WeaponBlueprint } from './weapon-kit'

/** 枪管轴线高度 */
const AXIS = 0.064
/** 枪身半宽 */
const HALF = 0.022

/**
 * 生成 QBZ-95 的模型蓝图。
 * @returns 枪身聚合物、黑色聚合物、发黑钢、橡胶四个图层与枪口位置
 */
export function buildQbz95(): WeaponBlueprint {
  const body = createLayer('polymer', { color: 0x2c322d }, [8, 8])
  const black = createLayer('polymer', { color: 0x141517, roughness: 0.62 }, [8, 8])
  const metal = createLayer('gunmetal', {}, [6, 6])
  const rubber = createLayer('rubber', {}, [10, 10])

  /* ── 枪身 ── */

  // 一体式枪身：托底在最后，弹匣井在握把后方，前端接护木
  body.add(
    profile(
      outline([
        [-0.305, 0.096, 0.008],
        [-0.305, -0.022, 0.01],
        [-0.215, -0.006, 0.004],
        [-0.118, -0.006, 0.004],
        [-0.105, 0.016, 0.004],
        [0.105, 0.016, 0.004],
        [0.115, 0.024],
        [0.12, 0.024],
        [0.12, 0.096],
      ]),
      HALF * 2,
      { bevel: 0.004, bevelSegments: 2 },
    ),
  )
  // 护木：向前收细
  body.add(
    loft(
      [
        sec(0.11, 0.02, 0.096, 0.0215, 3.5),
        sec(0.2, 0.024, 0.094, 0.0215, 3.2),
        sec(0.27, 0.03, 0.09, 0.019, 3),
        sec(0.285, 0.036, 0.088, 0.016, 3),
      ],
      { segments: 24 },
    ),
  )
  // 枪身两侧的纵向压筋；左侧贴腮处多一道
  for (const side of [-1, 1]) body.add(box(0.0014, 0.004, 0.19, side * 0.0224, 0.034, 0, 0.0005))
  body.add(box(0.0014, 0.004, 0.15, 0.0224, 0.08, -0.2, 0.0005))
  // 护木两侧的散热槽
  for (const side of [-1, 1]) {
    for (const z of [0.145, 0.186]) {
      for (const y of [0.05, 0.068]) rubber.add(box(0.0012, 0.005, 0.03, side * 0.0214, y, z, 0.0004))
    }
  }
  // 橡胶托底
  rubber.add(
    loft(
      [
        sec(-0.323, -0.016, 0.09, 0.0175, 3.5),
        sec(-0.319, -0.024, 0.098, 0.0225, 3.5),
        sec(-0.304, -0.024, 0.098, 0.0225, 3.5),
      ],
      { segments: 24 },
    ),
  )

  // 右侧抛壳窗：窗框、露出的枪机、后方的抛壳挡板
  metal.add(
    profile(rect(-0.2, -0.13, 0.056, 0.09, 0.004), 0.0016, {
      bevel: 0.0005,
      x: -0.0224,
      holes: [rect(-0.195, -0.135, 0.061, 0.085, 0.003)],
    }),
  )
  metal.add(box(0.0008, 0.024, 0.06, -0.0222, 0.073, -0.165, 0.0003))
  metal.add(box(0.004, 0.026, 0.006, -0.0235, 0.073, -0.204, 0.001))

  // 螺钉与销轴（贯穿两侧，略微凸出）
  const pins: readonly Pt[] = [
    [-0.282, 0.07],
    [-0.282, 0],
    [-0.225, 0.03],
    [-0.1, 0.045],
    [-0.02, 0.05],
    [0.06, 0.05],
    [0.1, 0.036],
  ]
  for (const [z, y] of pins) metal.add(rod(0.0027, [-0.0228, y, z], [0.0228, y, z], 10))

  // 快慢机（枪身左后方）
  metal.add(rod(0.006, [HALF, 0.04, -0.262], [0.0246, 0.04, -0.262], 12))
  metal.add(box(0.0018, 0.005, 0.02, 0.0252, 0.04, -0.252, 0.0006))

  /* ── 提把与瞄具 ── */

  // 一体式提把：后端是照门座，中间掏空
  body.add(
    profile(
      outline([
        [-0.2, 0.09],
        [0.112, 0.09],
        [0.104, 0.12, 0.006],
        [0.07, 0.176, 0.012],
        [-0.15, 0.184, 0.004],
        [-0.2, 0.184, 0.01],
      ]),
      0.018,
      {
        bevel: 0.003,
        bevelSegments: 2,
        holes: [
          outline([
            [-0.13, 0.104, 0.012],
            [0.068, 0.104, 0.012],
            [0.05, 0.158, 0.012],
            [-0.13, 0.164, 0.012],
          ]),
        ],
      },
    ),
  )
  // 照门：两片护耳 + 觇孔
  for (const side of [-1, 1]) metal.add(box(0.003, 0.014, 0.012, side * 0.0065, 0.19, -0.178, 0.0008))
  metal.add(shell(0.005, 0.0018, -0.181, -0.1785, 0.1885, 0, 12))
  // 提把下方的拉机柄
  metal.add(
    profile(
      outline(
        [
          [0, 0.103],
          [0.036, 0.103],
          [0.036, 0.112, 0.002],
          [0.012, 0.112, 0.002],
          [0.008, 0.124, 0.002],
          [0, 0.124, 0.002],
        ],
        2,
      ),
      0.014,
      { bevel: 0.001 },
    ),
  )

  // 准星座、环形护圈、准星
  metal.add(
    profile(
      outline(
        [
          [0.246, 0.086],
          [0.28, 0.086],
          [0.272, 0.168, 0.004],
          [0.254, 0.168, 0.004],
        ],
        2,
      ),
      0.011,
      { bevel: 0.0012 },
    ),
  )
  metal.add(shell(0.0125, 0.0105, 0.255, 0.271, 0.1785, 0, 24))
  metal.add(rod(0.0013, [0, 0.167, 0.263], [0, 0.181, 0.263], 8))

  /* ── 枪管 ── */

  // 护木前箍
  metal.add(
    loft(
      [
        sec(0.283, 0.04, 0.086, 0.0145, 3),
        sec(0.2845, 0.0385, 0.0875, 0.0158, 3),
        sec(0.29, 0.0385, 0.0875, 0.0158, 3),
        sec(0.2915, 0.04, 0.086, 0.0145, 3),
      ],
      { segments: 20 },
    ),
  )
  // 枪管与导气箍
  metal.add(
    lathe(
      [
        [0.1, 0.009],
        [0.298, 0.009],
        [0.298, 0.0135],
        [0.316, 0.0135],
        [0.316, 0.009],
        [0.386, 0.009],
      ],
      AXIS,
      0,
      20,
    ),
  )
  // 导气箍下的刺刀座、左侧背带环
  metal.add(box(0.008, 0.01, 0.016, 0, 0.047, 0.307, 0.0012))
  metal.add(ring(0.006, 0.0012, 0.0165, AXIS, 0.287, 'z', 14, 6))
  // 消焰器：带内膛，中段两道环槽
  metal.add(
    lathe(
      [
        [0.378, 0.0102],
        [0.384, 0.0125],
        [0.398, 0.0125],
        [0.399, 0.0115],
        [0.402, 0.0115],
        [0.403, 0.0125],
        [0.412, 0.0125],
        [0.413, 0.0115],
        [0.416, 0.0115],
        [0.417, 0.0125],
        [0.4285, 0.0125],
        [0.43, 0.0112],
        [0.43, 0.0052],
        [0.395, 0.0052],
        [0.395, 0],
      ],
      AXIS,
      0,
      20,
    ),
  )

  /* ── 握把与护圈 ── */

  body.add(
    loft(
      [
        { t: -0.1, c: -0.036, a: 0.019, w: 0.0135, n: 3 },
        { t: -0.096, c: -0.035, a: 0.022, w: 0.016, n: 3 },
        { t: -0.06, c: -0.022, a: 0.0215, w: 0.016, n: 3 },
        { t: -0.02, c: -0.009, a: 0.021, w: 0.0155, n: 3 },
        { t: 0.018, c: 0.003, a: 0.022, w: 0.0155, n: 3 },
      ],
      { axis: 'y', segments: 20 },
    ),
  )
  // 从握把底部绕到护木下方的大护圈
  body.add(
    profile(
      outline(
        [
          [-0.03, -0.098],
          [0.102, -0.098, 0.028],
          [0.102, 0.02],
          [0.091, 0.02],
          [0.091, -0.087, 0.018],
          [-0.03, -0.087],
        ],
        5,
      ),
      0.012,
      { bevel: 0.002, bevelSegments: 2 },
    ),
  )
  // 扳机
  metal.add(
    profile(
      outline(
        [
          [0.034, 0.018],
          [0.043, 0.018],
          [0.0415, 0.004, 0.004],
          [0.038, -0.01, 0.003],
          [0.041, -0.018, 0.002],
          [0.037, -0.019, 0.002],
          [0.033, -0.008, 0.004],
          [0.0345, 0.006, 0.004],
        ],
        2,
      ),
      0.006,
      { bevel: 0.0008 },
    ),
  )

  /* ── 弹匣（握把后方） ── */

  // 弧形弹匣：圆心在前方，越往下越向前弯
  const magZ = 0.09
  const magY = 0.02
  black.add(profile(arcBand(magZ, magY, 0.226, 0.274, -0.05, 0.68, 10), 0.026, { bevel: 0.002 }))
  black.add(profile(arcBand(magZ, magY, 0.24, 0.26, 0.08, 0.64, 10), 0.0285, { bevel: 0.0012 }))
  black.add(profile(arcBand(magZ, magY, 0.2235, 0.2765, 0.672, 0.7, 1), 0.029, { bevel: 0.001 }))
  // 弹匣后方的卡榫扳把
  metal.add(
    profile(
      outline(
        [
          [-0.223, 0.002],
          [-0.212, 0.002],
          [-0.21, -0.028, 0.003],
          [-0.216, -0.034, 0.002],
          [-0.222, -0.03, 0.002],
        ],
        2,
      ),
      0.01,
      { bevel: 0.0008 },
    ),
  )
  // 托底左侧背带环
  metal.add(ring(0.007, 0.0013, 0.0235, 0.082, -0.288, 'z', 14, 6))

  return { layers: [body.build(), black.build(), metal.build(), rubber.build()], muzzle: [0.43, AXIS] }
}
